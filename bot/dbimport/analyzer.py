class CategoryTagger:
    """Классификация записи по категории (max по числу совпадений)."""

    def __init__(self):
        # Для каждой категории список regex: совпадение по границе слова,
        # текст перед сравнением приводится к нижнему регистру.
        self._patterns = {
            category: [re.compile(r"\b" + re.escape(w.strip().lower()))
                       for w in words if w.strip()]
            for category, words in CATEGORIES.items()
        }

    def tag(self, text: str) -> str:
        """Возвращает категорию для текста. Без совпадений — 'Прочее'."""
        text_lower = (text or "").lower()
        # Хештеги: #крипта → категория по началу слова
        for hashtag in re.findall(r"#([\w.-]+)", text_lower):
            tags = " ".join(hashtag.replace("-", " ").split())
            category = self.tag(tags)
            if category != DEFAULT_SECTION:
                return category

        best, best_score = DEFAULT_SECTION, 0
        for category, patterns in self._patterns.items():
            score = sum(1 for p in patterns if p.search(text_lower))
            if score > best_score:
                best, best_score = category, score
        return best


_tagger: Optional[CategoryTagger] = None


def get_tagger() -> CategoryTagger:
    global _tagger
    if _tagger is None:
        _tagger = CategoryTagger()
    return _tagger


def analyze_records(records: list[dict]) -> list[dict]:
    """Проставляет каждому record['section'] — категория/раздел."""
    tagger = get_tagger()
    for rec in records:
        rec["section"] = tagger.tag(rec.get("text", ""))
    return records


def count_sections(records: list[dict]) -> list[str]:
    """Порядок категорий в порядке первого появления."""
    seen: list[str] = []
    for rec in records:
        name = rec.get("section") or DEFAULT_SECTION
        if name not in seen:
            seen.append(name)
    return seen